import { parseTextArt } from './text-art';

// ---------------------------------------------------------------------------
// Font
// ---------------------------------------------------------------------------

/** The character code of a solid block, the boot screen's cursor. */
export const BLOCK_CHAR = 127;

/**
 * The demo's own 8x8 font, as 128 characters of 8 bytes: character code `c`
 * is bytes `c * 8` to `c * 8 + 7`, top row first, high bit leftmost, the
 * layout of the chip's character set. Codes are ASCII; only capitals,
 * digits and some punctuation are drawn, and the text writers map lowercase
 * to capitals. Squared letters with two-pixel stems, drawn for this demo:
 * the machine's own character ROM is someone else's work.
 */
export const FONT: Uint8Array = buildFont();

// ---------------------------------------------------------------------------
// Internals
// ---------------------------------------------------------------------------

function buildFont(): Uint8Array {
    const font = new Uint8Array(128 * 8);
    const sections = glyphArt().split('[');
    for (let s = 1; s < sections.length; s++) {
        const section = sections[s];
        const close = section.indexOf(']');
        const name = section.slice(0, close);
        const code = name === 'block' ? BLOCK_CHAR : name.charCodeAt(0);
        if (name.length !== 1 && name !== 'block') throw new Error(`font glyph name "${name}" is not one character`);
        const art = parseTextArt({ text: section.slice(close + 1), inks: 'x' });
        if (art.width !== 8 || art.height !== 8) {
            throw new Error(`font glyph "${name}" is ${art.width}x${art.height}, not 8x8`);
        }
        for (let row = 0; row < 8; row++) {
            let bits = 0;
            for (let col = 0; col < 8; col++) bits = (bits << 1) | art.pixels[row * 8 + col];
            font[code * 8 + row] = bits;
        }
    }
    return font;
}

