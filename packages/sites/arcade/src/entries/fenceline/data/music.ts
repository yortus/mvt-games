import { createAudio80Song, type Audio80SongOptions } from 'audio90';
import { BANJO, BRUSH, FIDDLE, HORN, KICK, THUMP, TOCK } from './sounds';

// Fenceline's music was written for this game. The tunes are country
// breakdowns in G, for a band of four: a fiddle on the tune, a banjo
// picking rolls, a bass on the beat and a drum kit played with brushes.
// That leaves the chip's other four voices for the sound effects. Each row
// is a sixteenth note, with a cell for each channel. See audio90's
// guide, Writing Tracker Music, for the notation.

// ---------------------------------------------------------------------------
// The band
// ---------------------------------------------------------------------------

const BAND = {
    instruments: { F: FIDDLE, J: BANJO, B: THUMP, H: HORN, k: KICK, s: BRUSH, h: TOCK },
    filters: {
        // Takes the edge off the fiddle's saw
        a: { mode: 'lowpass', cutoffHz: 2400, resonance: 0.2, drive: 0.1 },
        // Swept shut by each banjo note, for its twang
        b: { mode: 'lowpass', cutoffHz: 1000, resonance: 0.45, drive: 0 },
    },
    // At 120 BPM, a dotted eighth lasts 375 ms, so the echo falls in time with the meadow tune
    echo: { timeMs: 375, feedback: 0.2, level: 0.25 },
} satisfies Partial<Audio80SongOptions>;

// ---------------------------------------------------------------------------
// Songs
// ---------------------------------------------------------------------------

