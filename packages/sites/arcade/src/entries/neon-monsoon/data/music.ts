import { type Audio90SongOptions, createAudio90Song } from '@mvtjs/audio';
import { BASS, BELLS, CRASH, EPIANO, HAT, KICK, LEAD, PAD, SNARE, STORM_HIT } from './instruments';

// Neon Monsoon's music was written for this game, mostly in D minor, in the
// style of the synth-driven shooters of the 1990s. It plays on the Audio90,
// in its console character. The songs have up to seven channels: an FM lead,
// chords played as arpeggios on FM bells and held on a pad, an
// octave-jumping FM bass, drums and hats, and accents: a crash at the start
// of each part, and an orchestra hit in the boss's theme. That leaves the
// chip's other nine voices for the storm of sound effects. The lead and the
// bells ring in an echo that bounces from side to side, a dotted eighth
// behind. Each row is a sixteenth note, and has a cell for each channel. See
// @mvtjs/audio's guide, Writing Tracker Music, for the notation.

// ---------------------------------------------------------------------------
// The band
// ---------------------------------------------------------------------------

const BAND = {
    instruments: { L: LEAD, C: BELLS, P: PAD, E: EPIANO, B: BASS, k: KICK, s: SNARE, h: HAT, x: CRASH, H: STORM_HIT },
    // Each channel's place: the bells to the left, the pad to the right, the
    // lead, bass and drums in the middle, and the hats and accents a little
    // to either side
    mixer: [
        { pan: 0, echo: 0.35, reverb: 0.2 },
        { pan: -0.55, echo: 0.4, reverb: 0.3 },
        { pan: 0.5, chorus: 0.6, reverb: 0.4 },
        { pan: 0 },
        { pan: 0, reverb: 0.1 },
        { pan: 0.35 },
        { pan: -0.25, reverb: 0.35 },
    ],
    // A dotted eighth, bouncing from side to side, at every song's tempo
    echo: { timeBeats: 3 / 4, feedback: 0.4, toneHz: 3500, isPingPong: true, level: 0.45 },
    reverb: { size: 0.55, decayMs: 1600, level: 0.3 },
    chorus: { depth: 0.5, rateHz: 0.6, level: 0.5 },
    character: 'console',
} satisfies Partial<Audio90SongOptions>;

/** The slow tune's band: the piano, the bells, the pad and the bass. */
const SLOW_BAND = {
    ...BAND,
    mixer: BAND.mixer.slice(0, 4),
} satisfies Partial<Audio90SongOptions>;

