import { createSong, type SongOptions } from '@mvtjs/audio';
import { PIPE, PIZZ, TIP } from './sounds';

// Crumb Chase's music. There are four pieces, all written for this game. Three
// are in D minor, and the tune for a cleared maze is in D major. Each uses two
// channels. One carries a lead or a high tiptoe, and the other a plucked bass.
// That leaves the chip's other six voices for the nibbles. The sneaking tune
// plays under the chase, and the game's audio view speeds it up as the maze
// empties. Each pattern is a list of rows, read from top to bottom, with one
// cell per channel in each row. Each row is a sixteenth note. See Writing
// Tracker Music, in @mvtjs/audio's docs, for the notation.

// ---------------------------------------------------------------------------
// The band
// ---------------------------------------------------------------------------

const BAND = {
    instruments: { P: PIPE, T: TIP, Z: PIZZ },
    // At 120 BPM, 250 ms is an eighth note, so the echo falls in time with the sneaking tune
    echo: { timeMs: 250, feedback: 0.3, level: 0.35 },
} satisfies Partial<SongOptions>;

// ---------------------------------------------------------------------------
// Songs
// ---------------------------------------------------------------------------

/**
 * The sneaking tune, played under the chase. Its bass tiptoes in eighth notes,
 * with a high note now and then. It loops, and its third time through is a
 * fourth higher.
 */
export const SNEAK = createSong({
    ...BAND,
    // The tune is written quiet. This lifts it to the loudness every song shares
    volume: 2.4,
    bpm: 120,
    patterns: {
        // The bass walks the D minor chord, stepping a half step aside and back
        a: `
            # high  | bass
            # ------------
            | ...   | D-2 Z
            | ...   | ...
            | ...   | F-2
            | A-5 T | ...
            | ...   | A-2
            | ...   | ...
            | ...   | G#2
            | ...   | ...
            | ...   | A-2
            | ...   | ...
            | ...   | F-2
            | F-5   | ...
            | ...   | D-2
            | ...   | ...
            | ...   | C#2
            | ...   | ...

            | ...   | D-2
            | ...   | ...
            | ...   | F-2
            | D-6   | ...
            | ...   | A-2
            | ...   | ...
            | ...   | B-2
            | ...   | ...
            | ...   | C-3
            | ...   | ...
            | ...   | A-2
            | C#6   | ...
            | ...   | G#2
            | ...   | ...
            | ...   | A-2
            | ...   | ...
        `,
    },
    order: ['a', 'a', 'a+5', 'a'],
    loop: 0,
});

/** The tune played as a game starts. It climbs the D minor chord to the D above, then winds back down to D. */
