import { createSong, type SongOptions } from '@mvtjs/audio';
import { BASS, CHIME, SPARKLE } from './sounds';

// The fruit machine's jingles, all written for this machine. They are short,
// and all in C. Each uses three channels, for a chime, chords played as
// arpeggios, and a bass. That leaves the chip's other five voices for the
// sound effects. Each row is a sixteenth note, with one cell per channel.
// See Writing Tracker Music, in @mvtjs/audio's docs, for the notation.

// ---------------------------------------------------------------------------
// The band
// ---------------------------------------------------------------------------

const BAND = {
    instruments: { C: CHIME, S: SPARKLE, B: BASS },
    echo: { timeMs: 180, feedback: 0.35, level: 0.4 },
} satisfies Partial<SongOptions>;

// ---------------------------------------------------------------------------
// Songs
// ---------------------------------------------------------------------------

/** A win. The chime climbs the C major chord, in a little under a bar. */
export const WIN = createSong({
    ...BAND,
    bpm: 160,
    patterns: {
        win: `
            # chime     | chords    | bass
            # ----------------------------
            | C-5 C v9  | C-4 S a47 | C-3 B
            | ...       | ...       | ...
            | E-5       | ...       | ...
            | ...       | ...       | ...
            | G-5       | ...       | G-2
            | ...       | ...       | ...
            | C-6 ~     | ...       | C-3
            | ...       | ...       | ...
            | ...       | ...       | ...
            | ...       | ...       | ...
            | ...       | ...       | ...
            | ...       | ...       | ...
            | ===       | ===       | ===
            | ...       | ...       | ...
        `,
    },
    order: ['win'],
});

