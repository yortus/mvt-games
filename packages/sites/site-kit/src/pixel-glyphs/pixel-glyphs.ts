// The site's pixel glyphs: every printable ASCII character, drawn here from
// scratch as rows of cells, for entries that set their text in pixels, as
// the games of the 1970s to the 1990s did. Each entry draws them its own
// way: sprites cut from a sheet that a generator script draws, rectangles in
// a Pixi `Graphics`, or a canvas. So this module draws nothing itself, and
// loads no renderer.

// ---------------------------------------------------------------------------
// Measures
// ---------------------------------------------------------------------------

