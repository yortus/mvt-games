/** The glyph of character code `code`, or undefined for a character with none. */
export function findGlyph(code: number): readonly string[] | undefined {
    return code >= FIRST_GLYPH_CODE && code <= LAST_GLYPH_CODE ? PIXEL_GLYPHS[code - FIRST_GLYPH_CODE] : undefined;
}

/**
 * The filled cells of `glyph`, as runs along its rows, each `[x, y, width]`
 * in cells from its top left: fewer shapes to draw than one a cell.
 */
export function listGlyphRuns(glyph: readonly string[]): (readonly [number, number, number])[] {
    const runs: (readonly [number, number, number])[] = [];
    for (let y = 0; y < glyph.length; y++) {
        const row = glyph[y];
        let start = -1;
        for (let x = 0; x <= row.length; x++) {
            const isFilled = x < row.length && row[x] === '#';
            if (isFilled && start < 0) start = x;
            if (!isFilled && start >= 0) {
                runs.push([start, y, x - start]);
                start = -1;
            }
        }
    }
    return runs;
}
