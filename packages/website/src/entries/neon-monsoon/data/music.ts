import { createSong, type SongOptions } from '@mvtjs/audio';
import { BASS, BELLS, EPIANO, HAT, KICK, LEAD, SNARE } from './sounds';

// Neon Monsoon's music was written for this game, mostly in D minor, in the
// style of the synth-driven shooters of the 1990s. The songs have up to four
// channels. They are a saw lead through a filter, chords played as arpeggios
// on an FM-like bell, an octave-jumping bass through a filter that closes on
// each note, and drums. That leaves the chip's other four voices for the
// storm of sound effects. A long echo sits under everything. Each row is a
// sixteenth note, and has a cell for each channel. See @mvtjs/audio's guide,
// Writing Tracker Music, for the notation.

// ---------------------------------------------------------------------------
// The band
// ---------------------------------------------------------------------------

const BAND = {
    instruments: { L: LEAD, C: BELLS, P: EPIANO, B: BASS, k: KICK, s: SNARE, h: HAT },
    filters: {
        // The bass's filter. The bass sweeps its cutoff down on each note
        a: { mode: 'lowpass', cutoffHz: 700, resonance: 0.55, drive: 0.15 },
        // The lead's filter. It is open enough to sing, and closed enough to keep the saw soft
        b: { mode: 'lowpass', cutoffHz: 2200, resonance: 0.25 },
    },
    // 300 ms is a dotted eighth at the stage theme's 150 BPM. Every song
    // shares this echo, so it falls a little off the beat at the other tempos
    echo: { timeMs: 300, feedback: 0.45, level: 0.45 },
} satisfies Partial<SongOptions>;

// ---------------------------------------------------------------------------
// Songs
// ---------------------------------------------------------------------------

