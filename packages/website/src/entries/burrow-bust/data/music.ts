import { createSong, type SongOptions } from '@mvtjs/audio';
import { BOUNCE, PLINK, SING, TOCK } from './sounds';

// Burrow Bust's music, written for this game. It is bouncy, in C, and plays
// on three channels: a lead, a bass and a tock. That leaves the chip's other
// five voices for the sound effects. The walking tune's lead and bass are
// plucks that die away by themselves. The game moves the tune on only while
// the digger moves, so it falls quiet when the digger stops. Each row is a
// sixteenth note, with a cell for each channel. See @mvtjs/audio's guide,
// Writing Tracker Music, for the notation.

// ---------------------------------------------------------------------------
// The band
// ---------------------------------------------------------------------------

const BAND = {
    instruments: { L: PLINK, S: SING, B: BOUNCE, t: TOCK },
    echo: { timeMs: 200, feedback: 0.3, level: 0.35 },
} satisfies Partial<SongOptions>;

// ---------------------------------------------------------------------------
// Songs
// ---------------------------------------------------------------------------

/** The walking tune. It loops through four bars, and moves on only while the digger moves. */
export const WALK_TUNE = createSong({
    ...BAND,
    // Its plucks die away, so it is turned up to be as loud as the other songs
    volume: 1.6,
    bpm: 140,
    patterns: {
        // Up the C chord, and down through F to G
        a: `
            # lead      | bass      | tock
            # ----------------------------
            | C-5 L v9  | C-3 B     | t
            | ...       | ...       | ...
            | E-5       | ...       | ...
            | ...       | ...       | ...
            | G-5       | G-2       | t
            | ...       | ...       | ...
            | E-5       | ...       | ...
            | ...       | ...       | ...
            | F-5       | F-2       | t
            | ...       | ...       | ...
            | A-5       | ...       | ...
            | ...       | ...       | ...
            | G-5       | G-2       | t
            | ...       | ...       | ...
            | E-5       | ...       | ...
            | ...       | ...       | ...
        `,
        // A minor round to C
        b: `
            | A-4       | A-2       | t
            | ...       | ...       | ...
            | C-5       | ...       | ...
            | ...       | ...       | ...
            | E-5       | E-2       | t
            | ...       | ...       | ...
            | C-5       | ...       | ...
            | ...       | ...       | ...
            | D-5       | G-2       | t
            | ...       | ...       | ...
            | B-4       | ...       | ...
            | ...       | ...       | ...
            | C-5       | C-3       | t
            | ...       | ...       | ...
            | ...       | ...       | ...
            | ...       | ...       | ...
        `,
        // Down the scale to C, then a G that leads back to the start
        c: `
            | E-5       | C-3       | t
            | ...       | ...       | ...
            | D-5       | ...       | ...
            | ...       | ...       | ...
            | C-5       | G-2       | t
            | ...       | ...       | ...
            | B-4       | ...       | ...
            | ...       | ...       | ...
            | C-5       | C-3       | t
            | ...       | ...       | ...
            | ...       | ...       | ...
            | ...       | ...       | ...
            | G-4       | G-2       | t
            | ...       | ...       | ...
            | ...       | ...       | ...
            | ...       | ...       | ...
        `,
    },
    order: ['a', 'b', 'a', 'c'],
    loop: 0,
});

