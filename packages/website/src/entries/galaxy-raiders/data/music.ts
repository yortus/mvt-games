import { createSong, type SongOptions } from '@mvtjs/audio';
import { BASS, CHORD, HAT, KICK, LEAD, SNARE } from './sounds';

// Galaxy Raiders' music. There are four pieces, all written for this game.
// Each uses four channels. They carry a lead, chords played as arpeggios, a
// filtered bass, and drums. That leaves the chip's other four voices for the
// sound effects. Each pattern is a list of rows, read from top to bottom, with
// one cell per channel in each row. See Writing Tracker Music, in
// @mvtjs/audio's docs, for the notation.

// ---------------------------------------------------------------------------
// The band
// ---------------------------------------------------------------------------

const BAND = {
    instruments: { L: LEAD, C: CHORD, B: BASS, k: KICK, s: SNARE, h: HAT },
    filters: { a: { mode: 'lowpass', cutoffHz: 1200, resonance: 0.6, drive: 0.3 } },
    // At 150 BPM, 300 ms is a dotted eighth, so the echo falls in time
    echo: { timeMs: 300, feedback: 0.35, level: 0.4 },
    // The songs are written loud. This brings them down to the loudness every song shares
    volume: 0.75,
} satisfies Partial<SongOptions>;

// ---------------------------------------------------------------------------
// Songs
// ---------------------------------------------------------------------------

