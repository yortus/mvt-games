import { createSong, type SongOptions } from '@mvtjs/audio';
import { BASS, CHORD, FLUTE, KOTO, RIM, SHAKER, TAIKO } from './sounds';

// Dojo Duel's music. Every piece is written for this game. The pieces are in
// A, and mostly use the Japanese "in" scale, whose notes are A, B flat, D, E
// and F. Each uses four channels. They carry a plucked lead or a flute, chords
// played as arpeggios, a plucked bass, and a taiko drum with hand percussion.
// That leaves the chip's other four voices for the fight's sounds. Each
// pattern is a list of rows, read from top to bottom, with one cell per
// channel in each row. A row is a sixteenth note, unless a song sets
// `rowsPerBeat`. See Writing Tracker Music, in @mvtjs/audio's docs, for the
// notation.

// ---------------------------------------------------------------------------
// The band
// ---------------------------------------------------------------------------

const BAND = {
    instruments: { K: KOTO, F: FLUTE, C: CHORD, B: BASS, t: TAIKO, r: RIM, h: SHAKER },
    filters: { a: { mode: 'lowpass', cutoffHz: 900, resonance: 0.5, drive: 0.2 } },
    // At 132 BPM, an eighth note lasts about 230 ms, so the echo falls in time with the fight's tune
    echo: { timeMs: 230, feedback: 0.4, level: 0.4 },
} satisfies Partial<SongOptions>;

// ---------------------------------------------------------------------------
// Songs
// ---------------------------------------------------------------------------

